_HANDLE = re.compile(r"@\w+")
_URL    = re.compile(r"https?://\S+")

# או שאין לפני זה אות עברית בכלל, או שיש בדיוק תחילית אחת בראש מילה.
_PREFIX_OK = r'(?:(?<![א-ת])|(?<=[\s"\'־-][הבלוכשמ]))'


def normalize(text):
    """מסיר @handles ו-URLs - שם המשתמש הוא לא תוכן הציוץ, והוא מקור תוצאות השווא."""
    # רווח מוביל: הופך "הגול" בתחילת ציוץ למילה עם תחילית שה-lookbehind רואה.
    return " " + _URL.sub(" ", _HANDLE.sub(" ", text or ""))


def _pat(term):
    # תחילית עברית חוקית היא אות אחת מ-הבלוכשמ בראש מילה: "הגול" כן, "ריגול" לא.
    left = _PREFIX_OK if term in _PREFIXED else ""
    if re.match(r"^[a-z ]+$", term):
        return re.compile(r"\b" + re.escape(term) + r"\b", re.I)
    # גבול מימין, אחרת "גול" בולע את גולן/גולדקנופף/גולגולת/רמת הגולן.
    right = "" if term in _STEMS else r"(?![א-ת])"
    if term == "מונדיאל":
        right = _NOT_MONDIALITO            # רבים כן, טורניר עד גיל 20 לא
    return re.compile(left + re.escape(term) + right)


_CORE_P   = [(t, _pat(t)) for t in CORE]
_STRONG_P = [(t, _pat(t)) for t in STRONG]
_WEAK_P   = [(t, _pat(t)) for t in WEAK]


def signals(text):
    """מחזיר (core, strong, weak) - המילים שנמצאו בכל שכבה, אחרי ניקוי."""
    t = normalize(text)
    return ([k for k, p in _CORE_P   if p.search(t)],
            [k for k, p in _STRONG_P if p.search(t)],
            [k for k, p in _WEAK_P   if p.search(t)])
